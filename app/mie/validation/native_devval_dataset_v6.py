def _group(raw):
    _need(type(raw) is NativeDevvalSourceGroupV6)
    # Gate3 canonical bytes remove insignificant Decimal trailing zeros. Use
    # that same numeric representation before the original feature replay
    # hashes its model JSON, both on first construction and saved replay.
    # Original source bytes, hashes and decision cutoffs remain unchanged.
    return NativeDevvalSourceGroupV6.model_validate_json(raw.canonical_json_bytes())


def _validate_group_lineage(group):
    """Replay exact saved source, never treat a DTO as a runtime capability."""
    receipt_raw = base64.b64decode(group.receipt_base64, validate=True)
    receipt = OrdinalReceiptV6.model_validate_json(receipt_raw)
    evidence = replay_native_availability_v6(
        base64.b64decode(group.evidence_base64, validate=True),
        expected_sha256=group.evidence_sha256,
    )
    bundle = replay_native_availability_bundle_v6(
        base64.b64decode(group.bundle_base64, validate=True),
        expected_sha256=group.bundle_sha256,
    )
    forensic = replay_forensic_pack_v6(
        base64.b64decode(bundle.stage1_forensic_base64, validate=True),
        expected_sha256=bundle.stage1_forensic_sha256,
        expected_claim_sha256=bundle.ordinal_claim_sha256,
    )
    _need(
        receipt.reason == "captured"
        and receipt.forensic_status == "completed"
        and forensic.status == "completed"
        and tuple((item.name, item.sha256) for item in receipt.forensic_files)
        == forensic.files
        and receipt.stage1_forensic_sha256 == forensic.sha256,
        "native_devval_receipt_completion_or_forensics_changed",
    )
    source = bundle.clock_v4.source_v3.v2_capture
    validate_stamps(
        [evidence.final_ready.model_dump(), group.decision.cutoff.model_dump()]
    )
    _need(
        group.decision.cutoff.monotonic_ns - evidence.final_ready.monotonic_ns
        <= CONSUMER_LEASE_NS
    )
    health_fresh_at(evidence.final_health.raw_bytes(), group.decision.cutoff)
    expected_rows = tuple(
        PointInTimeBar(
            source_row_id="okx-public-minute:" + row.source_row_identity,
            source_row_sha256=row.source_row_sha256,
            instrument_id=source.instrument_id,
            available_at=ceil_native_utc(evidence.final_ready.utc_ns),
            bar=row.bar,
        )
        for row in source.rows
    )
    _need(
        receipt.canonical_json_bytes() == receipt_raw
        and receipt.status == "NATIVE_DURABLE_AVAILABLE"
        and receipt.claim_sha256
        == evidence.ordinal_claim_sha256
        == bundle.ordinal_claim_sha256
        and source.plan_sha256 == group.capture_plan.canonical_sha256()
        and evidence.source_clock_v4 == bundle.clock_v4
        and evidence.custody.bundle_sha256 == group.bundle_sha256
        and group.decision.source_rows_sha256 == source.source_rows_sha256
        and group.decision.ordinal_claim_sha256 == evidence.ordinal_claim_sha256
        and group.decision.stage1_forensic_sha256 == bundle.stage1_forensic_sha256
        and group.available_at == ceil_native_utc(evidence.final_ready.utc_ns)
        and group.rows == expected_rows,
        "native_devval_original_lineage_changed",
    )
    _need(
        tuple(sorted((item.name, item.sha256) for item in receipt.files))
        == tuple(
            sorted(
                (
                    ("bundle-v6.json", group.bundle_sha256),
                    ("evidence-v6.json", group.evidence_sha256),
                    ("final-health.json", evidence.final_health.raw_sha256),
                )
            )
        )
        and receipt.stage1_forensic_sha256 == bundle.stage1_forensic_sha256,
        "native_devval_receipt_inventory_changed",
    )


def materialize_native_devval_dataset_v6(
    *, plan, expected_plan_sha256, source_plan, groups, source_inventory_sha256
):
    """Pure actual aggregation/features; supplied bytes do not prove acquisition.

    Callers cannot ask for an earlier or later cutoff. Every row must already be
    available at its own immutable original decision; features use the maximum
    of those decisions. Input order is validated, never sorted or deduplicated.
    """
    _need(type(plan) is NativeDevvalDatasetPlanV6)
    plan = NativeDevvalDatasetPlanV6.model_validate(plan.model_dump(mode="python"))
    _need(plan.canonical_sha256() == expected_plan_sha256, "native_devval_plan_changed")
    source_plan = checked_development_validation_source_plan(
        source_plan, expected_sha256=plan.source_plan_sha256
    )
    _need(type(groups) is tuple and len(groups) == len(source_plan.coordinates))
    groups = tuple(_group(group) for group in groups)
    _need(bool(groups))
    as_of = max(ceil_native_utc(group.decision.cutoff.utc_ns) for group in groups)
    row_inventory = hashlib.sha256()
    row_count = 0
    selected = {
        (window.partition.value, symbol): []
        for window in plan.windows
        for symbol in plan.instruments
    }
    identities = set()
    for ordinal, group in enumerate(groups):
        _validate_group_lineage(group)
        coordinate = source_plan.coordinate(ordinal)
        _need(
            group.ordinal == ordinal
            and group.capture_plan.canonical_bytes()
            == coordinate.capture_plan.canonical_bytes()
            and group.capture_plan.environment == plan.environment
            and group.capture_plan.volume_unit == plan.volume_unit,
            "native_devval_coordinate_unit_or_environment_changed",
        )
        matches = [
            window
            for window in plan.windows
            if window.partition.value == coordinate.partition
        ]
        _need(len(matches) == 1)
        window = matches[0]
        key = (coordinate.partition, group.capture_plan.instrument_id)
        _need(key in selected)
        for offset, row in enumerate(group.rows, start=1):
            # Source rows retain their source order. An overlap, gap, conflict,
            # swapped symbol or unexpected boundary is a refusal, never repair.
            identity = (row.instrument_id, row.bar.closed_at)
            _need(
                identity not in identities,
                "native_devval_duplicate_or_conflicting_coordinate",
            )
            identities.add(identity)
            expected_ns = group.capture_plan.start_ns + offset * 60_000_000_000
            epoch = datetime(1970, 1, 1, tzinfo=row.bar.closed_at.tzinfo)
            delta = row.bar.closed_at - epoch
            actual_ns = (
                (delta.days * 86400 + delta.seconds) * 1_000_000 + delta.microseconds
            ) * 1000
            _need(
                row.instrument_id == group.capture_plan.instrument_id
                and actual_ns == expected_ns
                and window.start_at < row.bar.closed_at <= window.end_at
                and row.available_at <= ceil_native_utc(group.decision.cutoff.utc_ns),
                "native_devval_missing_reordered_or_late_minute",
            )
            bound = BoundMinute(
                row=row,
                availability=AvailabilityProvenance(
                    basis=AvailabilityBasis.MEASURED_ROW_RECEIPT,
                    source_row_sha256=row.source_row_sha256,
                    receipt_sha256=group.evidence_sha256,
                    bar_closed_at=row.bar.closed_at,
                    observed_at=row.available_at,
                    retrieved_at=row.available_at,
                    available_at=row.available_at,
                ),
            )
            selected[key].append(bound)
            encoded = canonical(
                (
                    ordinal,
                    row.source_row_id,
                    row.source_row_sha256,
                    bound.canonical_sha256(),
                )
            )
            row_inventory.update(len(encoded).to_bytes(8, "big"))
            row_inventory.update(encoded)
            row_count += 1
    _need(row_count == source_plan.expected_rows)
    series = []
    for window in plan.windows:
        for symbol in plan.instruments:
            minutes = tuple(selected[(window.partition.value, symbol)])
            total = int((window.end_at - window.start_at).total_seconds()) // 60
            _need(len(minutes) == total, "native_devval_two_symbol_grid_incomplete")
            aggregation_plan = MinuteAggregationPlan(
                source_manifest_sha256=sha(
                    canonical([group.canonical_sha256() for group in groups])
                ),
                window=window,
                instrument_id=symbol,
                expected_minute_rows=total,
                volume_unit=plan.volume_unit,
            )
            minute_pin = minute_source_sha256(minutes)
            aggregation = aggregate_point_in_time_minutes(
                minutes,
                plan=aggregation_plan,
                expected_plan_sha256=aggregation_plan.canonical_sha256(),
                expected_source_sha256=minute_pin,
            )
            features = tuple(
                replay_features_at(
                    tuple(item.row for item in timeframe.bars),
                    bar_horizon=timeframe.horizon,
                    as_of=as_of,
                    history_bars=plan.history_bars,
                )
                for timeframe in aggregation.timeframes
            )
            series.append(
                NativeDevvalSeriesV6(
                    instrument_id=symbol,
                    window=window,
                    minutes=minutes,
                    minute_sha256=minute_pin,
                    aggregation=aggregation,
                    features=features,
                )
            )
    result = NativeDevvalDatasetV6(
        plan=plan,
        plan_sha256=expected_plan_sha256,
        source_plan=source_plan,
        source_inventory_sha256=source_inventory_sha256,
        groups=groups,
        series=tuple(series),
        frozen_as_of=as_of,
        row_inventory_sha256=row_inventory.hexdigest(),
    )
    frozen = _freeze(result, contract_type=NativeDevvalDatasetV6)
    _need(len(frozen.payload) <= _MAX_DATASET, "native_devval_dataset_budget")
    return frozen


def replay_native_devval_dataset_v6(payload, *, expected_sha256):
    """Read-only deterministic replay with the saved cutoff; never reads now."""
    _need(
        type(payload) is bytes and 0 < len(payload) <= _MAX_DATASET,
        "native_devval_dataset_budget",
    )
    dataset = _verify(
        payload, expected_sha256=expected_sha256, contract_type=NativeDevvalDatasetV6
    )
    rebuilt = materialize_native_devval_dataset_v6(
        plan=dataset.plan,
        expected_plan_sha256=dataset.plan_sha256,
        source_plan=dataset.source_plan,
        groups=dataset.groups,
        source_inventory_sha256=dataset.source_inventory_sha256,
    )
    _need(rebuilt.payload == payload, "native_devval_dataset_replay_changed")
    return rebuilt


def publish_native_devval_dataset_v6(*, root, payload, expected_sha256):
    """No-clobber inert retention with real readback; partial success is kept.

    Publication cannot renew the saved decision or prove a native acquisition.
    The existing native directory publisher supplies its existing platform and
    power-loss guarantees, rather than a new independent custody claim.
    """
    _need(type(root) is type(Path()))
    frozen = replay_native_devval_dataset_v6(payload, expected_sha256=expected_sha256)
    data = frozen.contract
    receipt = canonical(
        {
            "schema_version": "ctcc.mie.native_devval_dataset_publication.v6",
            "dataset_sha256": frozen.sha256,
            "dataset_bytes": len(frozen.payload),
            "plan_sha256": data.plan_sha256,
            "source_plan_sha256": data.plan.source_plan_sha256,
            "source_inventory_sha256": data.source_inventory_sha256,
            "row_inventory_sha256": data.row_inventory_sha256,
            "replay_grants_capability": False,
            "execution_authority": False,
        }
    )
    with _root_context(root) as directory:
        _need(not directory.names(), "native_devval_publication_not_empty")
        for name, raw in (
            ("dataset-v6.json", frozen.payload),
            ("receipt-v6.json", receipt),
            ("receipt-v6.sha256", sha(receipt).encode("ascii") + b"\n"),
        ):
            directory.publish(name, raw)
            _need(
                directory.read(name, _MAX_DATASET) == raw,
                "native_devval_publication_readback_failed",
            )
        _need(
            set(directory.names())
            == {"dataset-v6.json", "receipt-v6.json", "receipt-v6.sha256"}
        )
    return sha(receipt)


def _regular_bytes(path, maximum):
    _need(path.is_absolute())
    for parent in (path, *path.parents):
        metadata = parent.lstat()
        _need(
            not stat.S_ISLNK(metadata.st_mode)
            and not getattr(metadata, "st_file_attributes", 0) & 0x400
        )
    before = path.stat()
    _need(
        stat.S_ISREG(before.st_mode)
        and before.st_nlink == 1
        and 0 < before.st_size <= maximum
    )
    with path.open("rb") as stream:
        opened = os.fstat(stream.fileno())
        data = stream.read(maximum + 1)
        closed = os.fstat(stream.fileno())
    after = path.stat()

    def identity(value):
        return (
            value.st_dev,
            value.st_ino,
            value.st_size,
            value.st_mtime_ns,
            value.st_ctime_ns,
            value.st_mode,
            value.st_nlink,
            getattr(value, "st_file_attributes", None),
            getattr(value, "st_reparse_tag", None),
        )

    samples = (before, opened, closed, after)
    _need(
        all(
            stat.S_ISREG(value.st_mode)
            and value.st_nlink == 1
            and not getattr(value, "st_file_attributes", 0) & 0x400
            and not getattr(value, "st_reparse_tag", 0)
            for value in samples
        )
    )
    path_identity = identity(after)
    descriptor_identity = identity(closed)
    # Path stat and descriptor fstat expose distinct ctime semantics on
    # Windows Python 3.12. Each API must stay exact across the read, and
    # both independent ctimes remain in the returned inventory baseline.
    _need(
        identity(before) == path_identity
        and identity(opened) == descriptor_identity
        and path_identity[:4] + path_identity[5:]
        == descriptor_identity[:4] + descriptor_identity[5:]
        and len(data) == before.st_size
    )
    if os.name == "nt":
        # Windows has an explicit creation timestamp with the same meaning
        # through both APIs. Missing metadata cannot stand in for a match.
        birthtimes = tuple(getattr(value, "st_birthtime_ns", None) for value in samples)
        _need(
            all(type(value) is int for value in birthtimes)
            and all(
                type(getattr(value, field, None)) is int
                for value in samples
                for field in ("st_file_attributes", "st_reparse_tag")
            )
            and len(set(birthtimes)) == 1
        )
        creation_identity = birthtimes[0]
    else:
        _need(path_identity == descriptor_identity)
        creation_identity = None
    return data, (path_identity, descriptor_identity, creation_identity), sha(data)


def _source_inventory():
    """Whole source-prefix inventory, including extra files, plus exact manifest."""
    manifest, manifest_identity, manifest_hash = _regular_bytes(
        _ROOT / "MANIFEST.sha256", 2 * 1024 * 1024
    )
    entries = {}
    for line in manifest.decode("ascii").splitlines():
        digest, separator, name = line.partition("  ")
        _need(
            separator
            and len(digest) == 64
            and all(c in "0123456789abcdef" for c in digest)
            and name not in entries
        )
        _need(
            name and not name.startswith(("/", "\\")) and ".." not in Path(name).parts
        )
        entries[name] = digest
    actual = []
    for prefix in _PREFIXES:
        directory = _ROOT / prefix
        # No namespace/link traversal: every encountered directory is verified
        # before descent, and every file must belong to the packaged manifest.
        for current, directories, filenames in os.walk(directory, followlinks=False):
            current_path = Path(current)
            for name in directories:
                metadata = (current_path / name).lstat()
                _need(
                    not stat.S_ISLNK(metadata.st_mode)
                    and not getattr(metadata, "st_file_attributes", 0) & 0x400
                )
            directories[:] = [name for name in directories if name != "__pycache__"]
            for name in filenames:
                if name.endswith((".pyc", ".pyo")):
                    continue
                path = current_path / name
                relative = path.relative_to(_ROOT).as_posix()
                raw, identity, digest = _regular_bytes(path, _MAX_FILE)
                _need(
                    entries.get(relative) == digest,
                    "native_devval_source_inventory_changed",
                )
                actual.append((relative, identity, digest))
    present = {row[0] for row in actual}
    for relative in _SOURCE_CLOSURE_FILES:
        if relative not in present:
            raw, identity, digest = _regular_bytes(_ROOT / relative, _MAX_FILE)  # noqa: RUF059 -- raw bytes are validated by the bounded reader.
            _need(
                entries.get(relative) == digest,
                "native_devval_source_inventory_changed",
            )
            actual.append((relative, identity, digest))
    expected = {name for name in entries if name.startswith(_PREFIXES)} | set(
        _SOURCE_CLOSURE_FILES
    )
    _need({row[0] for row in actual} == expected)
    return manifest_hash, manifest_identity, tuple(sorted(actual))


def _check_code():
    for name, function, code, defaults, keyword_defaults in _NATIVE_HELPER_GUARDS:
        if (
            getattr(native, name) is not function
            or function.__code__ is not code
            or function.__defaults__ is not defaults
            or function.__kwdefaults__ is not keyword_defaults
        ):
            raise NativeDatasetError("native_devval_function_changed")
    if native._DEVVAL_FUNCTION_PINS is not _NATIVE_HOOK_PINS:
        raise NativeDatasetError("native_devval_hook_inventory_changed")
    try:
        native._devval_check_runtime_pins_v6(_FUNCTION_PINS)
        native._devval_runtime_check_v6()
    except Exception:  # noqa: BLE001 - Fixed source boundary; no native paths or policy values.
        raise NativeDatasetError("native_devval_function_changed") from None


async def build_native_devval_dataset_v6(
    *, owner, source_plan, plan, expected_plan_sha256
):
    """Acquire genuine original capabilities and finish their original leases.

    There is no clock/provider/callback injection. All capabilities are consumed
    immediately; final original DB/file replay and materialization must finish
    within every original 5 s consumer lease and 120 s acquisition deadline.
    Multiple captures may therefore fail closed on a slow host. No cap changes.
    """
    _need(type(owner) is DevelopmentValidationAvailabilityOwnerV6)
    source_plan = checked_development_validation_source_plan(source_plan)
    _need(
        type(plan) is NativeDevvalDatasetPlanV6
        and plan.source_plan_sha256 == source_plan.canonical_sha256()
    )
    _need(plan.canonical_sha256() == expected_plan_sha256)
    _check_code()
    task = asyncio.current_task()
    _need(task is not None and not task.cancelling())
    bindings, groups, receipts = [], [], []
    try:
        inventory = _source_inventory()  # Expanded before the first acquisition.
        inventory_sha256 = sha(canonical(inventory))
        for ordinal in range(len(source_plan.coordinates)):
            _check_code()
            _need(_source_inventory() == inventory)
            eligibility = await owner.capture_once(
                ordinal=ordinal, expected_previous_receipt_sha256s=tuple(receipts)
            )
            # Validate held leaf/default/denial bindings immediately after
            # the capture await, before running the consumer or materializer.
            try:
                _check_code()
            except BaseException:
                native.discard_native_devval_group_v6(eligibility)
                raise
            # Synchronous burn/MOVE before another await or caller exposure.
            binding, data = native.consume_native_devval_group_v6(
                eligibility, expected_source_plan_sha256=source_plan.canonical_sha256()
            )
            bindings.append(binding)
            group = NativeDevvalSourceGroupV6.model_validate(data)
            groups.append(group)
            receipts.append(group.receipt_sha256)
            _check_code()
            _need(_source_inventory() == inventory)
        materialized = materialize_native_devval_dataset_v6(
            plan=plan,
            expected_plan_sha256=expected_plan_sha256,
            source_plan=source_plan,
            groups=tuple(groups),
            source_inventory_sha256=inventory_sha256,
        )
        journal_snapshots = []
        for binding in bindings:
            _check_code()
            journal_snapshots.append(
                await native.replay_native_devval_group_v6(binding)
            )
            _check_code()
            _need(asyncio.current_task() is task and not task.cancelling())
        _need(len(set(journal_snapshots)) == 1, "native_devval_final_journal_changed")
        _check_code()
        _need(_source_inventory() == inventory)
        # Synchronously burn all bindings and recheck every ORIGINAL deadline
        # after the last await, materialization and source-inventory read.
        native.finish_native_devval_groups_v6(tuple(bindings))
        _check_code()
        return materialized
    except asyncio.CancelledError:
        raise
    except Exception:  # noqa: BLE001 - No native/DB/private source details escape.
        raise NativeDatasetError("native_devval_dataset_unavailable") from None
    finally:
        for binding in bindings:
            native.discard_native_devval_group_v6(binding)


