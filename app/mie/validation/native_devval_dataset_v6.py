class NativeDatasetError(ValueError):
    """Fixed codes only; no native paths, SQL errors or source prices."""


def _need(value, code="native_devval_dataset_denied"):
    if not value:
        raise NativeDatasetError(code)


class NativeDevvalDatasetPlanV6(Gate3Contract):
    schema_version: Literal["ctcc.mie.native_devval_dataset_plan.v6"] = (
        "ctcc.mie.native_devval_dataset_plan.v6"
    )
    source_plan_sha256: Sha256
    instruments: tuple[Literal["BTC-USDT-SWAP", "ETH-USDT-SWAP"], ...]
    windows: tuple[PartitionWindow, ...] = Field(min_length=1, max_length=2)
    history_bars: Literal[21] = 21
    volume_unit: Literal["contracts"] = "contracts"
    environment: Literal["public_production"] = "public_production"

    @model_validator(mode="after")
    def complete_grid(self):
        if self.instruments != ("BTC-USDT-SWAP", "ETH-USDT-SWAP"):
            raise ValueError("native_devval_exact_two_symbol_grid_required")
        for index, window in enumerate(self.windows):
            if window.partition.value not in ("development", "validation"):
                raise ValueError("native_devval_holdout_forbidden")
            for boundary in (window.start_at, window.end_at):
                if boundary.hour % 4 or any(
                    (boundary.minute, boundary.second, boundary.microsecond)
                ):
                    raise ValueError("native_devval_complete_four_hour_grid_required")
            if window.end_at - window.start_at < timedelta(minutes=21 * 240):
                raise ValueError("native_devval_feature_warmup_incomplete")
            if index and self.windows[index - 1].end_at > window.start_at:
                raise ValueError("native_devval_windows_out_of_order_or_overlap")
        if len({window.partition for window in self.windows}) != len(self.windows):
            raise ValueError("native_devval_partition_duplicated")
        return self


class NativeDevvalSourceGroupV6(Gate3Contract):
    """Portable source data. Construction never establishes native ownership."""

    ordinal: int = Field(ge=0, le=31)
    capture_plan: PublicMinuteCapturePlanV1
    receipt_base64: str
    receipt_sha256: Sha256
    evidence_base64: str
    evidence_sha256: Sha256
    bundle_base64: str
    bundle_sha256: Sha256
    decision: FutureAvailabilityDecisionV6
    decision_sha256: Sha256
    rows: tuple[PointInTimeBar, ...] = Field(min_length=1, max_length=3000)
    available_at: datetime

    @model_validator(mode="after")
    def pins(self):
        for name in ("receipt", "evidence", "bundle"):
            raw = base64.b64decode(getattr(self, name + "_base64"), validate=True)
            if (
                not 0 < len(raw) <= _MAX_DATASET
                or sha(raw) != getattr(self, name + "_sha256")
                or base64.b64encode(raw).decode("ascii")
                != getattr(self, name + "_base64")
            ):
                raise ValueError("native_devval_retained_source_changed")
        decision = self.decision
        if (
            decision.canonical_sha256() != self.decision_sha256
            or decision.evidence_sha256 != self.evidence_sha256
            or decision.bundle_sha256 != self.bundle_sha256
            or decision.row_count != len(self.rows)
            or len(self.rows) != self.capture_plan.expected_rows
        ):
            raise ValueError("native_devval_source_decision_binding_changed")
        # Exactly the original consumer's native upper bound. No bar-close or
        # caller-now availability substitution is performed here.
        if utc_nanoseconds(self.available_at) > decision.cutoff.utc_ns:
            raise ValueError("native_devval_source_late_at_original_decision")
        if any(row.available_at != self.available_at for row in self.rows):
            raise ValueError("native_devval_row_availability_changed")
        return self


