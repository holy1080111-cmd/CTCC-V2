class _DevvalBindingV6(_Carrier):
    """Nonportable original-state binding; no renewed eligibility or deadline."""


def _devval_original_check(record):
    _devval_runtime_check_v6()
    _require(
        type(record) is dict
        and set(record) == {"original", "decision", "attempted", "replayed", "journal"}
    )
    _require((CONSUMER_LEASE_NS, ACQUISITION_BUDGET_SECONDS) == _DEVVAL_ORIGINAL_LIMITS)
    owner, evidence, bundle, receipt_pin = record["original"]
    _recheck(owner)
    now = _stamp()
    validate_stamps(
        [
            evidence.contract.final_ready.model_dump(),
            record["decision"].contract.cutoff.model_dump(),
            now.model_dump(),
        ]
    )
    _require(
        now.monotonic_ns - evidence.contract.final_ready.monotonic_ns
        <= CONSUMER_LEASE_NS
    )
    health_fresh_at(evidence.contract.final_health.raw_bytes(), now)
    owner.claim.state.reader.read(
        owner.claim.claim.ordinal, expected_receipt_sha256=receipt_pin
    )
    return owner, evidence, bundle, receipt_pin


def consume_native_devval_group_v6(eligibility, *, expected_source_plan_sha256):
    """Burn the original one-use consumer before exposing inert rows/bytes.

    MOVE retains the same original tuple and every original time anchor. It
    does not turn the 5 s consumer lease into the 120 s acquisition budget.
    """
    original = (
        _READY.get(eligibility)
        if type(eligibility) is NativeAvailabilityEligibilityV6
        else None
    )
    _require(original is not None)
    try:
        _devval_runtime_check_v6()
        owner, evidence, bundle, receipt_pin = original
        _require(
            owner.claim.state.reader.plan.canonical_sha256()
            == expected_source_plan_sha256
        )
        decision, rows = consume_for_current_future_decision_v6(
            eligibility, expected_evidence_sha256=evidence.sha256
        )
        record = {
            "original": original,
            "decision": decision,
            "attempted": False,
            "replayed": False,
            "journal": None,
        }
        _devval_original_check(record)
        receipt = owner.claim.state.reader.read(
            owner.claim.claim.ordinal, expected_receipt_sha256=receipt_pin
        )
        source = bundle.contract.clock_v4.source_v3.v2_capture
        coordinate = owner.claim.state.reader.plan.coordinate(owner.claim.claim.ordinal)
        _require(coordinate.capture_plan_sha256 == source.plan_sha256)
        binding = _DevvalBindingV6(_ISSUER)
        _DEVVAL_LIVE[binding] = record
        return binding, {
            "ordinal": owner.claim.claim.ordinal,
            "capture_plan": coordinate.capture_plan,
            "receipt_base64": base64.b64encode(receipt.canonical_json_bytes()).decode(
                "ascii"
            ),
            "receipt_sha256": receipt_pin,
            "evidence_base64": base64.b64encode(evidence.payload).decode("ascii"),
            "evidence_sha256": evidence.sha256,
            "bundle_base64": base64.b64encode(bundle.payload).decode("ascii"),
            "bundle_sha256": bundle.sha256,
            "decision": decision.contract,
            "decision_sha256": decision.sha256,
            "rows": rows,
            "available_at": ceil_native_utc(evidence.contract.final_ready.utc_ns),
        }
    except Exception:  # noqa: BLE001 - Original capability stays burned on any failure.
        _READY.pop(eligibility, None)
        raise NativeAvailabilityError("native_devval_original_consume_failed") from None


def replay_native_devval_group_v6(binding):
    """Reserve the only final DB replay attempt synchronously, before await."""
    record = _DEVVAL_LIVE.get(binding) if type(binding) is _DevvalBindingV6 else None
    if record is None or record["attempted"]:
        raise NativeAvailabilityError("native_devval_final_replay_already_used")
    record["attempted"] = True
    try:
        _devval_runtime_check_v6()
        return _replay_native_devval_group_v6(binding, record)
    except BaseException:
        _DEVVAL_LIVE.pop(binding, None)
        raise


async def _replay_native_devval_group_v6(binding, record):
    try:
        _require(_DEVVAL_LIVE.get(binding) is record)
        owner, evidence, bundle, receipt_pin = _devval_original_check(record)
        await _deployment_recheck(owner)
        _devval_original_check(record)
        await _custody_scope(owner)
        _devval_original_check(record)
        readback = await owner.custody.read_retained_bundle_by_pins(
            expected_sha256=bundle.sha256,
            proof_envelope_sha256=evidence.contract.custody.proof_sha256,
        )
        _devval_original_check(record)
        _require(readback.bundle_raw == bundle.payload)
        _require(
            replay_native_availability_bundle_v6(
                readback.bundle_raw, expected_sha256=bundle.sha256
            )
            == bundle.contract
        )
        source = bundle.contract.clock_v4.source_v3
        witness_rows = await _read_witness(owner, source)
        _devval_original_check(record)
        # Later captures legitimately append to this same immutable chain. The
        # original entire prefix must remain exact, and the full current chain
        # is replayed by the fixed original witness/journal readers.
        _require(
            tuple(witness_rows[: len(bundle.contract.witness_rows)])
            == bundle.contract.witness_rows
        )
        from app.mie.validation.post_publication_availability_v3 import (
            _observation,
            _pins,
        )

        observed = await owner.observation.read(
            **_pins(source.v2_capture, source.v2_capture_sha256)
        )
        _devval_original_check(record)
        _require(_observation(observed) == source.post_read_observation)
        checkpoint, files = snapshot_public_journal_v6(
            owner.claim.state.service._journal
        )
        _require(
            checkpoint.genesis_sha256 == bundle.contract.checkpoint.genesis_sha256
            and checkpoint.sequence >= bundle.contract.checkpoint.sequence
        )
        current = {item.path: (item.raw_sha256, item.raw_base64) for item in files}
        _require(
            all(
                current.get(item.path) == (item.raw_sha256, item.raw_base64)
                for item in bundle.contract.files
            )
        )
        owner.claim.state.reader.read(
            owner.claim.claim.ordinal, expected_receipt_sha256=receipt_pin
        )
        _devval_original_check(record)
        snapshot = sha(
            canonical(
                {
                    "checkpoint": checkpoint.model_dump(mode="json"),
                    "files": [(item.path, item.raw_sha256) for item in files],
                }
            )
        )
        record["journal"], record["replayed"] = snapshot, True
        return snapshot
    except asyncio.CancelledError:
        _DEVVAL_LIVE.pop(binding, None)
        raise
    except Exception:  # noqa: BLE001 - No automatic second replay or original token remint.
        _DEVVAL_LIVE.pop(binding, None)
        raise NativeAvailabilityError(
            "native_devval_final_source_replay_failed"
        ) from None


def finish_native_devval_groups_v6(bindings):
    """Final synchronous burn and ORIGINAL lease/source replay after last await."""
    _require(type(bindings) is tuple and bool(bindings) and len(bindings) <= 32)
    _require(len({id(binding) for binding in bindings}) == len(bindings))
    records = tuple(
        _DEVVAL_LIVE.pop(binding, None) if type(binding) is _DevvalBindingV6 else None
        for binding in bindings
    )
    _devval_runtime_check_v6()
    _require(all(record is not None for record in records))
    for record in records:
        owner, _, _, _ = _devval_original_check(record)
        _require(record["attempted"] is True and record["replayed"] is True)
        checkpoint, files = snapshot_public_journal_v6(
            owner.claim.state.service._journal
        )
        snapshot = sha(
            canonical(
                {
                    "checkpoint": checkpoint.model_dump(mode="json"),
                    "files": [(item.path, item.raw_sha256) for item in files],
                }
            )
        )
        _require(snapshot == record["journal"])
    _require(len({record["journal"] for record in records}) == 1)
    # A final check of all leases follows the last potentially expensive file
    # replay. Original readiness and claim deadlines are never reassigned.
    for record in records:
        _devval_original_check(record)


def discard_native_devval_group_v6(binding):
    """Cancellation cleanup only; cannot return a consumer token or retry."""
    if type(binding) is _DevvalBindingV6:
        _DEVVAL_LIVE.pop(binding, None)
    elif type(binding) is NativeAvailabilityEligibilityV6:
        _READY.pop(binding, None)


def _devval_data_pin_v6(value, depth=0):
    """Structural source policy pin; never call a foreign serializer."""
    from types import MappingProxyType

    from sqlalchemy.sql.elements import TextClause

    if depth > 24:
        raise NativeAvailabilityError("native_devval_runtime_policy_depth")
    kind = type(value)
    if value is None or kind in (str, bytes, int, bool, float):
        return kind, value
    if kind in (tuple, list):
        return kind, tuple(_devval_data_pin_v6(item, depth + 1) for item in value)
    if kind in (dict, MappingProxyType):
        return kind, tuple(
            (_devval_data_pin_v6(key, depth + 1), _devval_data_pin_v6(item, depth + 1))
            for key, item in value.items()
        )
    if kind in (set, frozenset):
        return kind, frozenset(_devval_data_pin_v6(item, depth + 1) for item in value)
    if kind is TextClause:
        return (
            kind,
            value.text,
            tuple(
                (
                    key,
                    id(item.type),
                    _devval_data_pin_v6(item.value, depth + 1),
                    item.required,
                    item.expanding,
                )
                for key, item in value._bindparams.items()
            ),
        )
    # Decimal parameters are immutable but must be pinned by exact value as
    # well as identity. Registries, engines, locks and modules remain identity
    # pins; legitimate private registry contents are not frozen or copied.
    from decimal import Decimal

    if kind is Decimal:
        return kind, value.as_tuple()
    return "exact_identity", id(value)


def _devval_callable_pin_v6(value):
    from types import FunctionType, MethodType

    if type(value) is MethodType:
        return "method", id(value.__self__), _devval_callable_pin_v6(value.__func__)
    if type(value) is property:
        return (
            "property",
            value,
            tuple(
                _devval_callable_pin_v6(item)
                for item in (value.fget, value.fset, value.fdel)
            ),
        )
    if type(value) is FunctionType:
        return (
            "function",
            value,
            value.__code__,
            id(value.__code__),
            id(value.__globals__),
            _devval_data_pin_v6(value.__defaults__),
            _devval_data_pin_v6(value.__kwdefaults__),
            tuple(
                (id(cell), id(cell.cell_contents)) for cell in (value.__closure__ or ())
            ),
        )
    return "data", _devval_data_pin_v6(value)


